function normalizeLegacyText(value) {
  if (typeof value === 'string') return LEGACY_TEXT.get(value) || value;
  if (Array.isArray(value)) return value.map(normalizeLegacyText);
  if (value && typeof value === 'object') {
    return Object.fromEntries(Object.entries(value).map(([key, child]) => [key, normalizeLegacyText(child)]));
  }
  return value;
}

function normalizeTenantSettings(settings) {
  if (!settings || typeof settings !== 'object') return settings || {};
  const normalized = normalizeLegacyText(settings);
  return normalized;
}

module.exports = { normalizeLegacyText, normalizeTenantSettings };
